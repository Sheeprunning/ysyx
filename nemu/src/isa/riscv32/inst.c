#define R(i) gpr(i)
#define Mr vaddr_read
#define Mw vaddr_write

#define MSTATUS 0x300
#define MTVEC   0x305
#define MEPC    0x341
#define MCAUSE  0x342

#define YIELD   11

enum {
  TYPE_I, TYPE_U, TYPE_S, TYPE_J, TYPE_R, TYPE_B,
  TYPE_N, // none
};


#define src1R() do { *src1 = R(rs1); } while (0)
#define src2R() do { *src2 = R(rs2); } while (0)
#define immI() do { *imm = SEXT(BITS(i, 31, 20), 12); } while(0)
#define immU() do { *imm = SEXT(BITS(i, 31, 12), 20) << 12; } while(0)
#define immS() do { *imm = (SEXT(BITS(i, 31, 25), 7) << 5) | BITS(i, 11, 7); } while(0)
#define immJ() do { *imm = SEXT( (BITS(i, 31, 31) << 20 | BITS(i, 19 , 12) <<  12 |\
                    BITS(i , 20 , 20) << 11 | BITS( i, 30 , 21) << 1 ), 21 ); } while(0)
#define immB() do { *imm = SEXT((BITS(i, 31, 31) <<12 | BITS(i,7,7)<<11 | \
                    BITS(i,30,25)<<5 | BITS(i,11,8)<<1),13); } while(0)

static void decode_operand(Decode *s, int *rd, word_t *src1, word_t *src2, word_t *imm, int type) {
  uint32_t i = s->isa.inst;
  int rs1 = BITS(i, 19, 15);
  int rs2 = BITS(i, 24, 20);
  *rd     = BITS(i, 11, 7);
  switch (type) {
    case TYPE_I: src1R();          immI(); break;
    case TYPE_U:                   immU(); break;
    case TYPE_S: src1R(); src2R(); immS(); break;
    case TYPE_J:                   immJ(); break;
    case TYPE_R: src1R(); src2R();         break; 
    case TYPE_B: src1R(); src2R(); immB(); break;
    case TYPE_N: break;
    default: panic("unsupported type = %d", type);
  }
}

static word_t csr_read(uint32_t csr){
  switch(csr){
    case MTVEC:  return cpu.csr.mtvec;
    case MCAUSE: return cpu.csr.mcause;
    case MSTATUS: return cpu.csr.mstatus;
    case MEPC: return cpu.csr.mepc;
    default: panic("unsupported read on csr = 0x%x", csr);
  }
}

static void csr_write(uint32_t csr,word_t data){
  switch(csr){
    case MTVEC:   cpu.csr.mtvec = data;  break;
    case MCAUSE:  cpu.csr.mcause = data;  break;
    case MSTATUS: cpu.csr.mstatus = data; break;
    case MEPC:    cpu.csr.mepc =data; break;
    default: panic("unsupported write on csr = 0x%x", csr);
  }
}

